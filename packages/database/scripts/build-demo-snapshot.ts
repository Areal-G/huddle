/**
 * Writes generated/demo-snapshot.ts: the demo database (every migration plus
 * the seed) as a gzipped PGlite data directory. Building it here keeps the
 * work out of serverless cold starts, which only load the snapshot.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { createDemoSnapshot } from "../src/demo-snapshot";

async function main() {
  const snapshot = await createDemoSnapshot();

  writeFileSync(
    path.join(__dirname, "../generated/demo-snapshot.ts"),
    `// Generated by scripts/build-demo-snapshot.ts. Do not edit.\nimport type { DemoSnapshot } from "../src/demo-snapshot";\n\nexport const demoSnapshot: DemoSnapshot = ${JSON.stringify(snapshot)};\n`,
  );

  console.info(
    `✓ Built demo snapshot (${Math.round(snapshot.data.length / 1024)} KB)`,
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
