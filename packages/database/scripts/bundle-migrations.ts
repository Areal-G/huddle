/**
 * Writes generated/migrations.ts: the SQL of every migration, in order, for
 * the demo database snapshot (src/demo-snapshot.ts). Bundling the SQL into code
 * spares the serverless functions from locating migration files at runtime.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const migrationsDir = path.join(__dirname, "../prisma/migrations");

const migrations = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()
  .map((name) =>
    readFileSync(path.join(migrationsDir, name, "migration.sql"), "utf8"),
  );

writeFileSync(
  path.join(__dirname, "../generated/migrations.ts"),
  `// Generated by scripts/bundle-migrations.ts. Do not edit.\nexport const migrations: string[] = ${JSON.stringify(migrations)};\n`,
);

console.info(`✓ Bundled ${migrations.length} migrations`);
